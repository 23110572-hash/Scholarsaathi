def _organization(
    key: str,
    display_name: str,
    organization_type: OrganizationType,
    state: str | None = None,
) -> dict[str, Any]:
    return {
        "key": key,
        "slug": f"{key}-scholarship-reference",
        "legal_name": f"{display_name} — Public-source reference catalogue",
        "display_name": f"{display_name} — Reference",
        "type": organization_type,
        "state": state,
        "publisher_login": f"{key}.catalog@demo.scholarsaathi.local",
    }


