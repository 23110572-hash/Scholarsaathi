    return {
        "slug": slug,
        "organization": organization,
        "title": title,
        "summary": summary,
        "states": states,
        "levels": levels,
        "courses": courses,
        "tags": tags,
        "official_source_url": official_source_url,
        "eligibility": eligibility,
        "benefit": benefit,
    }


